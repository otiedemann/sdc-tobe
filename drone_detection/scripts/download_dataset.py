#!/usr/bin/env python3
"""
Download and prepare the Seraphim Drone Detection Dataset for YOLO training.

Dataset: https://huggingface.co/datasets/lgrzybowski/seraphim-drone-detection-dataset
  - 83,483 images (75k train / 8.3k test)
  - YOLO format, 640x640, CC BY 4.0
  - Single class: "drone"

Usage:
    # Option A: automatic download via huggingface_hub (recommended)
    pip install huggingface_hub
    python download_dataset.py

    # Option B: manual download
    #   1. Go to https://huggingface.co/datasets/lgrzybowski/seraphim-drone-detection-dataset
    #   2. Download the dataset files
    #   3. Extract into drone_detection/data/seraphim/
    #   4. Run: python download_dataset.py --verify-only

After download, the directory structure will be:
    drone_detection/data/seraphim/
        train/
            images/    (75,000+ JPEGs)
            labels/    (75,000+ .txt YOLO annotations)
        test/
            images/    (8,300+ JPEGs)
            labels/    (8,300+ .txt YOLO annotations)
"""

import argparse
import os
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_DIR = SCRIPT_DIR.parent
DATA_DIR = PROJECT_DIR / "data" / "seraphim"

DATASET_REPO = "lgrzybowski/seraphim-drone-detection-dataset"


def download_hf():
    """Download dataset using huggingface_hub."""
    try:
        from huggingface_hub import snapshot_download
    except ImportError:
        print("ERROR: huggingface_hub not installed.")
        print("  pip install huggingface_hub")
        print()
        print("Or download manually from:")
        print(f"  https://huggingface.co/datasets/{DATASET_REPO}")
        sys.exit(1)

    print(f"Downloading Seraphim dataset to {DATA_DIR} ...")
    print(f"  Repository: {DATASET_REPO}")
    print(f"  This is ~9 GB — will take a while on slow connections.")
    print()

    snapshot_download(
        repo_id=DATASET_REPO,
        repo_type="dataset",
        local_dir=str(DATA_DIR),
        ignore_patterns=["*.md", ".gitattributes"],
    )
    print(f"\nDownload complete: {DATA_DIR}")


def verify_dataset():
    """Check dataset structure and count files."""
    ok = True
    total_images = 0
    total_labels = 0

    for split in ["train", "test"]:
        img_dir = DATA_DIR / split / "images"
        lbl_dir = DATA_DIR / split / "labels"

        if not img_dir.exists():
            print(f"  MISSING: {img_dir}")
            ok = False
            continue

        imgs = list(img_dir.glob("*.jpg")) + list(img_dir.glob("*.png"))
        lbls = list(lbl_dir.glob("*.txt")) if lbl_dir.exists() else []

        print(f"  {split}/images: {len(imgs)} files")
        print(f"  {split}/labels: {len(lbls)} files")
        total_images += len(imgs)
        total_labels += len(lbls)

        if len(imgs) == 0:
            print(f"    WARNING: No images in {split}!")
            ok = False
        if len(lbls) == 0:
            print(f"    WARNING: No labels in {split}!")
            ok = False
        if len(imgs) != len(lbls):
            print(f"    WARNING: image/label count mismatch in {split}!")

    print(f"\n  Total: {total_images} images, {total_labels} labels")

    # Check a sample label to verify YOLO format
    sample_lbl = None
    for split in ["train", "test"]:
        lbl_dir = DATA_DIR / split / "labels"
        if lbl_dir.exists():
            lbls = list(lbl_dir.glob("*.txt"))
            if lbls:
                sample_lbl = lbls[0]
                break

    if sample_lbl:
        content = sample_lbl.read_text().strip()
        if content:
            first_line = content.split("\n")[0]
            parts = first_line.split()
            if len(parts) == 5:
                cls, cx, cy, w, h = parts
                print(f"\n  Sample label ({sample_lbl.name}):")
                print(f"    class={cls} cx={cx} cy={cy} w={w} h={h}")
                print(f"    Format: YOLO (class cx cy w h) — OK")
            else:
                print(f"\n  WARNING: Unexpected label format: {first_line}")
    else:
        print("\n  Could not find sample label to verify format")

    return ok


def create_dataset_yaml():
    """Create the YOLO dataset YAML config."""
    yaml_path = PROJECT_DIR / "data" / "drone_dataset.yaml"
    yaml_content = f"""# Seraphim Drone Detection Dataset
# Auto-generated by download_dataset.py

path: {DATA_DIR}
train: train/images
val: test/images

names:
  0: drone

# Dataset info:
#   Source: https://huggingface.co/datasets/{DATASET_REPO}
#   Images: ~83,483 (75k train / 8.3k test)
#   Resolution: 640x640
#   License: CC BY 4.0
"""
    yaml_path.write_text(yaml_content)
    print(f"\nDataset YAML written to: {yaml_path}")
    return yaml_path


def main():
    parser = argparse.ArgumentParser(description="Download Seraphim Drone Detection Dataset")
    parser.add_argument("--verify-only", action="store_true",
                        help="Only verify existing dataset, don't download")
    parser.add_argument("--skip-download", action="store_true",
                        help="Skip download, just create YAML and verify")
    args = parser.parse_args()

    print("=" * 60)
    print("Seraphim Drone Detection Dataset Setup")
    print("=" * 60)
    print()

    if not args.verify_only and not args.skip_download:
        download_hf()
        print()

    print("Verifying dataset structure...")
    ok = verify_dataset()

    if ok:
        yaml_path = create_dataset_yaml()
        print()
        print("=" * 60)
        print("Dataset ready for training!")
        print(f"  YAML config: {yaml_path}")
        print()
        print("Next step — train with:")
        print(f"  python drone_detection/scripts/train.py")
        print("=" * 60)
    else:
        print()
        print("Dataset verification FAILED — check paths above.")
        if args.verify_only:
            print(f"\nExpected structure:")
            print(f"  {DATA_DIR}/train/images/*.jpg")
            print(f"  {DATA_DIR}/train/labels/*.txt")
            print(f"  {DATA_DIR}/test/images/*.jpg")
            print(f"  {DATA_DIR}/test/labels/*.txt")
        sys.exit(1)


if __name__ == "__main__":
    main()
